#include <stdio.h>

void func() {
	printf("Inside func\n");
}

int main() {
	printf("Before func\n");

//Разом із IP при виклику func() процесор кладе на стек адресу повернення
//Якби верхівка стека була замість IP (вказівника інструкцій),
//то тоді нікуди було б покласти адресу повернення, не затерши поточну команду.
//В результаті після func() програма не знайде дорогу назад,
//буде збій разом із помилкою.

	func();
	printf("After func\n");
}
